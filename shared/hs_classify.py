def normalize_maker(maker: str) -> str:
    """和英混在の maker 名を小文字キーに寄せる。未知はそのまま小文字化。"""
    m = (maker or "").strip().lower()
    if not m:
        return ""
    for k, v in _MAKER_ALIAS.items():
        if k in m:
            return v
    return m


_ALIAS_KEYS = frozenset(_MAKER_ALIAS.values())


def resolve_brand(shopify_brand: str, maker: str, jan: str = "",
                  jan_prefix_map: dict | None = None) -> str:
    """① Shopify の brand タグ → ② NST maker（_MAKER_ALIAS 命中）→ ③ JAN 事業者プレフィックス → ④ maker 小文字.

    源の版は maker が非空だと alias 不命中でも ② で返してしまい ③ に落ちなかった（仕様書 §6 のバグ）。
    jan_prefix_map の値は生の maker でも正規化済みキーでもよい（normalize_maker を通す）。
    """
    if shopify_brand:
        return shopify_brand.lower()
    nm = normalize_maker(maker)
    if nm and nm in _ALIAS_KEYS:
        return nm
    if jan and jan_prefix_map and len(jan) >= 7:
        pre = normalize_maker(jan_prefix_map.get(jan[:7]) or "")
        if pre:
            return pre
    return nm


def classify(jp_name: str, brand: str, maker: str) -> tuple[str | None, str]:
    """→ (品類, 根拠)。判定できなければ (None, 'none')."""
    jp_name = _norm(jp_name or "")
    # ⚠️ 順序が肝：**単品の日本語名が最優先**。ブランドは「その単品が何か」を
    # 決めない（CANMAKE も洗顔を出すし、花王は全品類ある）。ブランドは日本語名で
    # 決まらなかった時の受け皿にしか使わない。2026-09-19 に逆順で実装して誤判定。
    b = (brand or "").lower()
    _ex = _BRAND_EXCEPT.get(b)
    if b in BRAND_EXCLUSIVE and not (_ex and _ex.search(jp_name)):
        # 独占ブランドでも例外品はある（THERMOS の「保冷ランチバッグ」＝袋）。
        # その語が出たらブランドを譲って日本語名に任せる（Boss 2026-09-19 指摘）。
        return BRAND_EXCLUSIVE[b], "brand-x"
    for rx, cat in _JP:
        if rx.search(jp_name or ""):
            return cat, "jp-name"
    if b in BRAND_CAT:
        return BRAND_CAT[b], "brand"
    mk = (maker or "").lower()
    for k, v in BRAND_CAT.items():
        if k in mk:
            return v, "maker"
    return None, "none"


# ── 規格（plan_name_en.extract_spec の移植）──────────────────────
# 規格は **容量・重量だけ**（Boss 2026-09-19）。個数は報関名に書かない。
_RX_VOL = re.compile(r"(\d+(?:\.\d+)?)\s?(ml|mL|L|g|kg)(?![A-Za-z])")


def extract_spec(title: str) -> str:
    """容量・重量のみ返す。取れなければ空（個数は**書かない**）."""
    m = _RX_VOL.search(unicodedata.normalize("NFKC", title or ""))
    if not m:
        return ""
    num, unit = m.group(1), m.group(2)
    return f"{num}{'ml' if unit == 'mL' else unit}"


